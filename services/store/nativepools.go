type poolRow struct {
	runtimeapi.PoolMember
	retireBy  *time.Time
	revokedAt *time.Time
	retired   bool
}

func poolRows(ctx context.Context, tx pgx.Tx, org string) ([]poolRow, error) {
	rows, err := tx.Query(ctx, `SELECT p.seat_id,s.key,p.team_key,p.template_key,p.created_at,s.retire_by,s.retired_at IS NOT NULL,p.revoked_at,p.retained_until,p.purged_at FROM native_pool_members p JOIN seats s ON s.id=p.seat_id WHERE p.organization_id=$1 AND (s.retired_at IS NULL OR p.seat_id IN (
 SELECT recent.seat_id FROM native_pool_members recent JOIN seats rs ON rs.id=recent.seat_id
 WHERE recent.organization_id=$1 AND rs.retired_at IS NOT NULL ORDER BY recent.created_at DESC LIMIT 50
 )) ORDER BY p.created_at,p.seat_id`, org)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []poolRow
	for rows.Next() {
		var p poolRow
		if err = rows.Scan(&p.SeatID, &p.SeatKey, &p.Team, &p.Template, &p.CreatedAt, &p.retireBy, &p.retired, &p.revokedAt, &p.RetainedUntil, &p.PurgedAt); err != nil {
			return nil, err
		}
		p.State = "available"
		if p.retireBy != nil {
			p.State = "draining"
		}
		if p.retired {
			p.State = "retired"
		}
		out = append(out, p)
	}
	return out, rows.Err()
}
func cloneSpec(in spec.OrganizationSpec) spec.OrganizationSpec {
	raw, _ := json.Marshal(in)
	var out spec.OrganizationSpec
	_ = json.Unmarshal(raw, &out)
	return out
}
func poolSpec(in spec.OrganizationSpec, members []poolRow) spec.OrganizationSpec {
	out := cloneSpec(in)
	if out.Seats == nil {
		out.Seats = map[string]spec.Seat{}
	}
	if out.MemoryStores == nil {
		out.MemoryStores = map[string]spec.MemoryStore{}
	}
	for _, p := range members {
		if p.retired || p.retireBy != nil || p.revokedAt != nil {
			continue
		}
		team, ok := out.Teams[p.Team]
		if !ok || team.Pool == nil {
			continue
		}
		tpl, ok := team.Pool.Templates[p.Template]
		if !ok || tpl.Seat == nil {
			continue
		}
		seat := *tpl.Seat
		seat.Teams = append(slices.Clone(seat.Teams), p.Team)
		slices.Sort(seat.Teams)
		seat.Teams = slices.Compact(seat.Teams)
		seat.PersonalMemory = "private_" + strings.TrimPrefix(p.SeatKey, "pool_")
		out.Seats[p.SeatKey] = seat
		out.MemoryStores[seat.PersonalMemory] = spec.MemoryStore{Retention: "retain"}
	}
	return out
}
func addPoolMember(ctx context.Context, tx pgx.Tx, org string, m *compile.Manifest, team, template, requester, request string) (poolRow, error) {
	rows, err := poolRows(ctx, tx, org)
	if err != nil {
		return poolRow{}, err
	}
	p := poolRow{PoolMember: runtimeapi.PoolMember{SeatID: uuid.NewString(), Team: team, Template: template, State: "available"}}
	p.SeatKey = "pool_" + strings.ReplaceAll(p.SeatID, "-", "")
	// Compile the explicit template as an ordinary independent principal.
	rows = append(rows, p)
	effective, err := compile.Compile(poolSpec(m.Spec, rows), compile.DefaultCatalog())
	if err != nil {
		return p, fmt.Errorf("%w: pool template: %v", ErrInvalid, err)
	}
	markPoolManifests(effective, rows)
	sm := effective.Seats[p.SeatKey]
	id, _, err := upsertSeat(ctx, tx, org, m.Spec.Key, sm, nil)
	if err != nil {
		return p, err
	}
	// Seat UUID is generated by the ordinary identity creation path. The private
	// memory name remains unique to this participant, never to the requester.
	p.SeatID = id
	err = tx.QueryRow(ctx, `INSERT INTO native_pool_members(seat_id,organization_id,team_key,template_key,requested_by,request_id,retention_seconds) VALUES($1,$2,$3,$4,NULLIF($5,'')::uuid,NULLIF($6,'')::uuid,$7) RETURNING created_at`, id, org, team, template, requester, request, m.Spec.Teams[team].Pool.RetentionSeconds).Scan(&p.CreatedAt)
	return p, err
}

// reconcileNativePools runs under the organization lock. Capacity includes
// draining members, preventing replacement bursts from exceeding max_members.
func reconcileNativePools(ctx context.Context, tx pgx.Tx, org string, m *compile.Manifest) (*compile.Manifest, map[string]bool, error) {
	rows, err := poolRows(ctx, tx, org)
	if err != nil {
		return nil, nil, err
	}
	hasPool := len(rows) > 0
	for _, t := range m.Spec.Teams {
		hasPool = hasPool || t.Pool != nil
	}
	if !hasPool {
		return m, nil, nil
	}
	active, err := activeSeats(ctx, tx, org)
	if err != nil {
		return nil, nil, err
	}
	for _, p := range rows {
		if p.retired {
			continue
		}
		t, ok := m.Spec.Teams[p.Team]
		valid := ok && t.Pool != nil
		if valid {
			_, valid = t.Pool.Templates[p.Template]
		}
		if !valid {
			if err = revokePoolMember(ctx, tx, org, p, active[p.SeatKey]); err != nil {
				return nil, nil, err
			}
			continue
		}
		if p.revokedAt == nil {
			if _, err = tx.Exec(ctx, `UPDATE native_pool_members SET retention_seconds=$2 WHERE seat_id=$1`, p.SeatID, t.Pool.RetentionSeconds); err != nil {
				return nil, nil, err
			}
		}
		if p.retireBy != nil || p.revokedAt != nil {
			continue
		}
		var idle bool
		if t.Pool.IdleTimeoutSeconds > 0 {
			err = tx.QueryRow(ctx, `SELECT NOT EXISTS(SELECT 1 FROM deliveries WHERE seat_id=$1 AND state IN ('pending','leased')) AND NOT EXISTS(SELECT 1 FROM executions WHERE seat_id=$1 AND state='running') AND COALESCE((SELECT max(finished_at) FROM executions WHERE seat_id=$1),$2)<now()-make_interval(secs=>$3)`, p.SeatID, p.CreatedAt, t.Pool.IdleTimeoutSeconds).Scan(&idle)
			if err != nil {
				return nil, nil, err
			}
		}
		available := 0
		for _, q := range rows {
			if !q.retired && q.Team == p.Team {
				if q.retireBy == nil {
					available++
				}
			}
		}
		if t.Pool.Draining || available > t.Pool.MaxMembers || (idle && available > t.Pool.MinMembers) {
			grace := time.Duration(t.Pool.DrainTimeoutSeconds) * time.Second
			if _, err = beginRetirement(ctx, tx, org, p.SeatKey, active[p.SeatKey], grace); err != nil {
				return nil, nil, err
			}
			for i := range rows {
				if rows[i].SeatID == p.SeatID {
					now := time.Now()
					rows[i].retireBy = &now
				}
			}
		}
	}
	rows, err = poolRows(ctx, tx, org)
	if err != nil {
		return nil, nil, err
	}
	for _, team := range sortedKeys(m.Spec.Teams) {
		p := m.Spec.Teams[team].Pool
		if p == nil || p.Draining {
			continue
		}
		count, available := 0, 0
		for _, q := range rows {
			if !q.retired && q.Team == team {
				count++
				if q.retireBy == nil {
					available++
				}
			}
		}
		templates := sortedKeys(p.Templates)
		if len(templates) == 0 {
			continue
		}
		for available < p.MinMembers && count < p.MaxMembers {
			member, e := addPoolMember(ctx, tx, org, m, team, templates[0], "", "")
			if e != nil {
				return nil, nil, e
			}
			rows = append(rows, member)
			count++
			available++
		}
	}
	rows, err = poolRows(ctx, tx, org)
	if err != nil {
		return nil, nil, err
	}
	effective, err := compile.Compile(poolSpec(m.Spec, rows), compile.DefaultCatalog())
	if err != nil {
		return nil, nil, err
	}
	markPoolManifests(effective, rows)
	// Draining participants still checkpoint and finish their bounded turn.
	// Refresh their authority too, without cancelling retirement, so a policy
	// tightening cannot leave an old capability live for the grace period.
	policyRows := slices.Clone(rows)
	for i := range policyRows {
		policyRows[i].retireBy = nil
	}
	drainingPolicy, err := compile.Compile(poolSpec(m.Spec, policyRows), compile.DefaultCatalog())
	if err != nil {
		return nil, nil, err
	}
	markPoolManifests(drainingPolicy, policyRows)
	for _, p := range rows {
		if p.retired || p.retireBy == nil {
			continue
		}
		if cur := active[p.SeatKey]; cur != nil {
			copy := *cur
			copy.retireBy = nil
			if sm, ok := drainingPolicy.Seats[p.SeatKey]; ok {
				if _, _, err := upsertSeat(ctx, tx, org, m.Spec.Key, sm, &copy); err != nil {
					return nil, nil, err
				}
			}
		}
	}
	dynamic := map[string]bool{}
	for _, p := range rows {
		if !p.retired {
			dynamic[p.SeatKey] = true
		}
	}
	return effective, dynamic, nil
}

func poolAuthority(ctx context.Context, tx pgx.Tx, seatID, team string, mutate bool) (string, *compile.Manifest, error) {
	var org string
	var raw, seatRaw []byte
	err := tx.QueryRow(ctx, `SELECT o.id,o.manifest,s.manifest FROM organizations o JOIN seats s ON s.organization_id=o.id WHERE s.id=$1 AND s.retired_at IS NULL AND s.retiring_at IS NULL AND o.deleted_at IS NULL FOR UPDATE OF o`, seatID).Scan(&org, &raw, &seatRaw)
	if err != nil {
		return "", nil, notFound(err)
	}
	var m compile.Manifest
	var sm compile.SeatManifest
	if err = json.Unmarshal(raw, &m); err != nil {
		return "", nil, err
	}
	if err = json.Unmarshal(seatRaw, &sm); err != nil {
		return "", nil, err
	}
	t, ok := m.Spec.Teams[team]
	if !ok || t.Pool == nil || !slices.Contains(sm.Teams, team) {
		return "", nil, fmt.Errorf("%w: not a member of this pool team", ErrInvalid)
	}
	if mutate && (t.Coordination == nil || t.Coordination.Mode != "self_organising") {
		allowed := false
		if t.Coordination != nil {
			for _, subject := range t.Coordination.MissionEditors {
				allowed = allowed || policy.MatchesSubject(&sm, subject)
			}
		}
		if !allowed {
			return "", nil, fmt.Errorf("%w: pool admission requires an authorized team editor", ErrInvalid)
		}
	}
	return org, &m, nil
}
func (s *Store) ListPoolMembers(ctx context.Context, seatID, team string) ([]runtimeapi.PoolMember, error) {
	var out []runtimeapi.PoolMember
	err := s.inTx(ctx, func(tx pgx.Tx) error {
		org, _, err := poolAuthority(ctx, tx, seatID, team, false)
		if err != nil {
			return err
		}
		rows, err := poolRows(ctx, tx, org)
		if err != nil {
			return err
		}
		for _, p := range rows {
			if p.Team == team {
				out = append(out, p.PoolMember)
			}
		}
		return nil
	})
	return out, err
}
func (s *Store) SpawnPoolMember(ctx context.Context, f Fence, team, template, requestID string) (*runtimeapi.PoolMember, error) {
	if _, err := uuid.Parse(requestID); err != nil {
		return nil, fmt.Errorf("%w: request_id must be a UUID", ErrInvalid)
	}
	var out runtimeapi.PoolMember
	err := s.inTx(ctx, func(tx pgx.Tx) error {
		org, m, err := poolAuthority(ctx, tx, f.SeatID, team, true)
		if err != nil {
			return err
		}
		if err = checkFence(ctx, tx, f); err != nil {
			return err
		}
		var priorTeam, priorTemplate, id string
		err = tx.QueryRow(ctx, `SELECT seat_id,team_key,template_key FROM native_pool_members WHERE requested_by=$1 AND request_id=$2`, f.SeatID, requestID).Scan(&id, &priorTeam, &priorTemplate)
		if err == nil {
			if priorTeam != team || priorTemplate != template {
				return fmt.Errorf("%w: request_id reused", ErrConflict)
			}
			return tx.QueryRow(ctx, `SELECT p.seat_id,s.key,p.team_key,p.template_key,p.created_at,
                CASE WHEN s.retired_at IS NOT NULL THEN 'retired' WHEN s.retiring_at IS NOT NULL THEN 'draining' ELSE 'available' END,p.retained_until,p.purged_at
                FROM native_pool_members p JOIN seats s ON s.id=p.seat_id WHERE p.seat_id=$1`, id).
				Scan(&out.SeatID, &out.SeatKey, &out.Team, &out.Template, &out.CreatedAt, &out.State, &out.RetainedUntil, &out.PurgedAt)
		}
		if err != nil && err != pgx.ErrNoRows {
			return err
		}
		p := m.Spec.Teams[team].Pool
		if p.Draining {
			return fmt.Errorf("%w: pool draining", ErrConflict)
		}
		if _, ok := p.Templates[template]; !ok {
			return fmt.Errorf("%w: unknown template", ErrInvalid)
		}
		rows, err := poolRows(ctx, tx, org)
		if err != nil {
			return err
		}
		count := 0
		for _, p := range rows {
			if p.Team == team && !p.retired {
				count++
			}
		}
		if count >= p.MaxMembers {
			return fmt.Errorf("%w: pool capacity %d/%d including draining participants", ErrConflict, count, p.MaxMembers)
		}
		b := m.Spec.ModelBudgets
		if b == nil || b.OrganizationDailyOutputTokens <= 0 {
			return fmt.Errorf("%w: native pools require shared organization model budget", ErrInvalid)
		}
		var used int64
		err = tx.QueryRow(ctx, `SELECT COALESCE((SELECT charged_output_tokens FROM model_budget_counters WHERE organization_id=$1 AND scope='organization' AND scope_id=$1::text AND period_start=(clock_timestamp() AT TIME ZONE 'UTC')::date),0)`, org).Scan(&used)
		if err != nil {
			return err
		}
		if used >= b.OrganizationDailyOutputTokens {
			return &BudgetExhausted{Scope: "organization"}
		}
		member, err := addPoolMember(ctx, tx, org, m, team, template, f.SeatID, requestID)
		if err != nil {
			return err
		}
		out = member.PoolMember
		return refreshPoolManifests(ctx, tx, org, m)
	})
	return &out, err
}
func (s *Store) DrainPoolMember(ctx context.Context, f Fence, team, memberID string) error {
	return s.inTx(ctx, func(tx pgx.Tx) error {
		org, m, err := poolAuthority(ctx, tx, f.SeatID, team, true)
		if err != nil {
			return err
		}
		if err = checkFence(ctx, tx, f); err != nil {
			return err
		}
		rows, err := poolRows(ctx, tx, org)
		if err != nil {
			return err
		}
		available := 0
		for _, p := range rows {
			if p.Team == team && !p.retired && p.retireBy == nil {
				available++
			}
		}
		for _, p := range rows {
			if p.Team == team && p.SeatID == memberID {
				if p.retired || p.retireBy != nil {
					return nil
				}
				pool := m.Spec.Teams[team].Pool
				if !pool.Draining && available <= pool.MinMembers {
					return fmt.Errorf("%w: draining would breach min_members", ErrConflict)
				}
				active, err := activeSeats(ctx, tx, org)
				if err != nil {
					return err
				}
				_, err = beginRetirement(ctx, tx, org, p.SeatKey, active[p.SeatKey], time.Duration(m.Spec.Teams[team].Pool.DrainTimeoutSeconds)*time.Second)
				return err
			}
		}
		return ErrNotFound
	})
}
func refreshPoolManifests(ctx context.Context, tx pgx.Tx, org string, m *compile.Manifest) error {
	rows, err := poolRows(ctx, tx, org)
	if err != nil {
		return err
	}
	effective, err := compile.Compile(poolSpec(m.Spec, rows), compile.DefaultCatalog())
	if err != nil {
		return err
	}
	markPoolManifests(effective, rows)
	active, err := activeSeats(ctx, tx, org)
	if err != nil {
		return err
	}
	ids := map[string]runtimeapi.SeatIdentity{}
	retiring := map[string]string{}
	for _, key := range sortedKeys(effective.Seats) {
		id, rev, err := upsertSeat(ctx, tx, org, m.Spec.Key, effective.Seats[key], active[key])
		if err != nil {
			return err
		}
		ids[key] = runtimeapi.SeatIdentity{SeatID: id, PolicyRevision: rev}
	}
	for _, p := range rows {
		if p.retireBy != nil && !p.retired {
			if a := active[p.SeatKey]; a != nil {
				retiring[a.manifest.PersonalMemory] = a.id
			}
		}
	}
	return syncStores(ctx, tx, org, effective, ids, nil, retiring)
}

// PoolInstructions resolves operator-owned template guidance at bootstrap time,
// without delivering a message or spending tokens merely to keep a pool warm.
func (s *Store) PoolInstructions(ctx context.Context, seatID string) (string, error) {
	var text string
	err := s.pool.QueryRow(ctx, `SELECT COALESCE(o.manifest->'spec'->'teams'->p.team_key->'pool'->'templates'->p.template_key->>'instructions','') FROM native_pool_members p JOIN organizations o ON o.id=p.organization_id JOIN seats s ON s.id=p.seat_id WHERE p.seat_id=$1 AND s.retired_at IS NULL AND o.deleted_at IS NULL`, seatID).Scan(&text)
	if err == pgx.ErrNoRows {
		return "", nil
	}
	return text, err
}

func markPoolManifests(m *compile.Manifest, rows []poolRow) {
	for _, p := range rows {
		if sm, ok := m.Seats[p.SeatKey]; ok {
			sm.PoolTeam = p.Team
			sm.ConfigRevision = compile.Revision(sm)
			m.Seats[p.SeatKey] = sm
		}
	}
}

// revokePoolMember fences immediately but keeps retirement due until the normal
// finalizer releases owned work, returns delivery, retires private stores and
// publishes the retained handoff. Policy reintroduction cannot resurrect it.
func revokePoolMember(ctx context.Context, tx pgx.Tx, org string, p poolRow, seat *activeSeat) error {
	if p.revokedAt != nil {
		return nil
	}
	if _, err := beginRetirement(ctx, tx, org, p.SeatKey, seat, 0); err != nil {
		return err
	}
	if _, err := tx.Exec(ctx, `UPDATE seats SET retire_by=now() WHERE id=$1`, p.SeatID); err != nil {
		return err
	}
	if _, err := tx.Exec(ctx, `UPDATE native_pool_members SET revoked_at=now() WHERE seat_id=$1`, p.SeatID); err != nil {
		return err
	}
	if err := pendingSeatCredentials(ctx, tx, p.SeatID); err != nil {
		return err
	}
	for _, q := range []string{
		`UPDATE executions SET state='interrupted',error='pool authority revoked',finished_at=now() WHERE seat_id=$1 AND state='running'`,
		`UPDATE execution_leases SET generation=generation+1,holder='',expires_at='epoch',state='Revoked',state_detail='pool authority revoked',updated_at=now() WHERE seat_id=$1`,
		`UPDATE automations SET status='deleted',updated_at=now() WHERE seat_id=$1 AND status IN ('active','paused')`,
	} {
		if _, err := tx.Exec(ctx, q, p.SeatID); err != nil {
			return err
		}
	}
	return nil
}
